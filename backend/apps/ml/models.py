"""
Machine Learning and Predictive Analytics Models.

Provides enterprise model registry, versioning, evaluation telemetry,
prediction persistence, anomaly alert management, and asynchronous job tracking.
"""

from django.conf import settings
from django.db import models


class MLModelType(models.TextChoices):
    REVENUE_FORECAST = "REVENUE_FORECAST", "Time-Series Revenue Forecast"
    CHURN_PREDICTION = "CHURN_PREDICTION", "Customer Churn Classifier"
    ANOMALY_DETECTION = "ANOMALY_DETECTION", "Metric Anomaly Detector"


class MLApprovalStatus(models.TextChoices):
    DRAFT = "DRAFT", "Draft (Training in progress)"
    EVALUATED = "EVALUATED", "Evaluated (Awaiting Approval)"
    APPROVED = "APPROVED", "Approved for Production"
    REJECTED = "REJECTED", "Rejected"


class MLModel(models.Model):
    """
    Catalog entry for a registered machine learning capability.
    Tracks lineage, model category, and description.
    """

    id = models.BigAutoField(primary_key=True)
    name = models.CharField(max_length=255, unique=True)
    model_type = models.CharField(
        max_length=50,
        choices=MLModelType.choices,
        db_index=True,
    )
    description = models.TextField(blank=True, default="")
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "ml_models"
        verbose_name = "ML Model"
        verbose_name_plural = "ML Models"
        ordering = ["name"]

    def __str__(self):
        return f"{self.name} ({self.get_model_type_display()})"


class MLModelVersion(models.Model):
    """
    Specific trained artifact version with immutable evaluation metrics,
    baseline comparisons, feature metadata, and approval state.
    """

    id = models.BigAutoField(primary_key=True)
    model = models.ForeignKey(
        MLModel,
        on_delete=models.CASCADE,
        related_name="versions",
    )
    version = models.CharField(max_length=50)
    dataset_identifier = models.CharField(max_length=255, default="orders_v1")
    training_start_date = models.DateField(null=True, blank=True)
    training_end_date = models.DateField(null=True, blank=True)
    feature_names = models.JSONField(default=list, blank=True)
    hyperparameters = models.JSONField(default=dict, blank=True)
    evaluation_metrics = models.JSONField(default=dict, blank=True)
    baseline_metrics = models.JSONField(default=dict, blank=True)
    artifact_payload = models.JSONField(default=dict, blank=True)
    approval_status = models.CharField(
        max_length=50,
        choices=MLApprovalStatus.choices,
        default=MLApprovalStatus.EVALUATED,
        db_index=True,
    )
    is_active = models.BooleanField(default=False, db_index=True)
    notes = models.TextField(blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "ml_model_versions"
        verbose_name = "ML Model Version"
        verbose_name_plural = "ML Model Versions"
        unique_together = ("model", "version")
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.model.name} v{self.version} [{self.approval_status}]"


class MLPrediction(models.Model):
    """
    Audited prediction record generated by an approved ML model version.
    Stores target period or entity, predicted values, prediction intervals, and risk contributions.
    """

    id = models.BigAutoField(primary_key=True)
    model_version = models.ForeignKey(
        MLModelVersion,
        on_delete=models.CASCADE,
        related_name="predictions",
    )
    prediction_type = models.CharField(max_length=50, db_index=True)
    entity_id = models.CharField(max_length=255, blank=True, default="")
    target_period = models.CharField(max_length=50, blank=True, default="")
    predicted_value = models.FloatField(null=True, blank=True)
    prediction_interval_lower = models.FloatField(null=True, blank=True)
    prediction_interval_upper = models.FloatField(null=True, blank=True)
    risk_score = models.FloatField(null=True, blank=True)
    risk_level = models.CharField(max_length=50, blank=True, default="")
    contributing_features = models.JSONField(default=dict, blank=True)
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        db_table = "ml_predictions"
        verbose_name = "ML Prediction"
        verbose_name_plural = "ML Predictions"
        ordering = ["-created_at"]


class MLAnomalyAlert(models.Model):
    """
    Alert record for detected anomalies in business metrics.
    Supports user acknowledgment and historical tracking.
    """

    id = models.BigAutoField(primary_key=True)
    metric_name = models.CharField(max_length=100, db_index=True)
    alert_timestamp = models.DateTimeField(db_index=True)
    observed_value = models.FloatField()
    baseline_value = models.FloatField()
    deviation_score = models.FloatField()
    severity = models.CharField(
        max_length=50,
        choices=[
            ("LOW", "Low"),
            ("MEDIUM", "Medium"),
            ("HIGH", "High"),
            ("CRITICAL", "Critical"),
        ],
        default="MEDIUM",
    )
    context_summary = models.TextField(blank=True, default="")
    is_acknowledged = models.BooleanField(default=False, db_index=True)
    acknowledged_at = models.DateTimeField(null=True, blank=True)
    acknowledged_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "ml_anomaly_alerts"
        verbose_name = "ML Anomaly Alert"
        verbose_name_plural = "ML Anomaly Alerts"
        ordering = ["-alert_timestamp"]


class MLJob(models.Model):
    """
    Background job execution record for training, backtesting, and batch prediction.
    Tracks status, progress, retries, and execution logs.
    """

    id = models.BigAutoField(primary_key=True)
    job_type = models.CharField(max_length=50, db_index=True)
    status = models.CharField(
        max_length=50,
        choices=[
            ("PENDING", "Pending"),
            ("RUNNING", "Running"),
            ("SUCCESS", "Success"),
            ("FAILED", "Failed"),
            ("CANCELLED", "Cancelled"),
        ],
        default="PENDING",
        db_index=True,
    )
    progress_pct = models.IntegerField(default=0)
    parameters = models.JSONField(default=dict, blank=True)
    result_summary = models.JSONField(default=dict, blank=True)
    error_message = models.TextField(null=True, blank=True)
    logs = models.TextField(blank=True, default="")
    started_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    retry_count = models.IntegerField(default=0)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "ml_jobs"
        verbose_name = "ML Job"
        verbose_name_plural = "ML Jobs"
        ordering = ["-created_at"]
